import { expect, test } from "bun:test";
import { chmodSync, mkdirSync, readFileSync, readdirSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { setup } from "./install-setup.ts";

// POSIX-only: the fixture runs scripts/install-source.sh and shebang stubs through a ':' PATH.
const posix = test.skipIf(process.platform === "win32");

// A side home next to another Cataly, so the installer takes the side path that generates omp.yml.
function withOtherCataly(home: string) {
  mkdirSync(join(home, ".cataly"));
  writeFileSync(join(home, ".cataly/config.json"), '{"owner":"another Cataly"}\n');
  mkdirSync(join(home, "skills"));
  symlinkSync("/elsewhere/cataly-mode", join(home, "skills/cataly-mode"));
  mkdirSync(join(home, "global-bin"));
  symlinkSync("/elsewhere/cli.ts", join(home, "global-bin/cataly"));
}

posix("a fresh side install writes the managed skills block, with no owner keys added", () => {
  // Given another Cataly's ~/.cataly and no omp.yml in the side home yet.
  const { home, install } = setup();
  withOtherCataly(home);
  // When scripts/install-source.sh runs in side mode.
  const r = install({ CATALY_INSTALL_MODE: "side" });
  // Then the generated bytes and complete parsed content contain exactly the three managed keys.
  expect(r.code).toBe(0);
  const expected = {
    skills: { ignoredSkills: ["cataly-mode"], customDirectories: [join(home, ".omp-cataly/skills")] },
    update: { auto: false },
  };
  const text = readFileSync(join(home, ".omp-cataly/omp.yml"), "utf8");
  expect(text).toBe(
    `# Generated by scripts/install-source.sh for omp-cataly omp sessions; skills paths and update.auto are managed.\n${Bun.YAML.stringify(expected, null, 2)}\n`,
  );
  expect(Bun.YAML.parse(text)).toEqual(expected);
});

posix("a reinstall refreshes the managed keys and keeps every key the owner added", () => {
  // Given a side install whose owner then added roles, a thinking level and an unrelated skills key.
  const { home, install } = setup();
  withOtherCataly(home);
  expect(install({ CATALY_INSTALL_MODE: "side" }).code).toBe(0);
  const path = join(home, ".omp-cataly/omp.yml");
  const owner = {
    modelRoles: { default: "anthropic/claude-opus-5-5:medium", task: "deploy/deepseek-v4.1-flash-1017:max" },
    defaultThinkingLevel: "auto",
    update: { auto: true, channel: "canary", interval: 0 },
    "0": { kept: "index-looking owner key" },
    owner: { enabled: false, empty: "", nothing: null, nested: [0, false, null, { custom: "value" }] },
  };
  const before = Bun.YAML.parse(readFileSync(path, "utf8")) as { skills: object };
  writeFileSync(
    path,
    Bun.YAML.stringify(
      {
        ...before,
        ...owner,
        skills: { ignoredSkills: ["stale"], customDirectories: ["/stale"], extra: ["x"], enabled: false },
      },
      null,
      2,
    ),
  );
  chmodSync(path, 0o640);
  const mode = statSync(path).mode & 0o777;
  // When the same side install runs again.
  const r = install({ CATALY_INSTALL_MODE: "side" });
  // Then the owner's keys survive, the unrelated skills key survives, and only the managed keys are refreshed.
  expect(r.code).toBe(0);
  expect(Bun.YAML.parse(readFileSync(path, "utf8"))).toEqual({
    ...owner,
    skills: {
      extra: ["x"],
      enabled: false,
      ignoredSkills: ["cataly-mode"],
      customDirectories: [join(home, ".omp-cataly/skills")],
    },
    update: { ...owner.update, auto: false },
  });
  expect(statSync(path).mode & 0o777).toBe(mode);
});

posix("a reinstall leaves the owner configuration visible until the merged file is ready", () => {
  const { root, home, install } = setup();
  withOtherCataly(home);
  expect(install({ CATALY_INSTALL_MODE: "side" }).code).toBe(0);
  const path = join(home, ".omp-cataly/omp.yml");
  const previous = "modelRoles:\n  default: owner/model\nupdate:\n  auto: true\n";
  writeFileSync(path, previous);
  const inode = statSync(path).ino;
  const observed = join(root, "observed-omp.yml");
  const bun = join(root, "bin/bun");
  writeFileSync(
    bun,
    readFileSync(bun, "utf8").replace(
      "#!/bin/sh\n",
      `#!/bin/sh\nif [ "\${1##*/}" = source-configuration.ts ] && [ "\${2:-}" = publish-yaml ]; then cp "$3/omp.yml" ${JSON.stringify(observed)}; fi\n`,
    ),
  );
  const result = install({ CATALY_INSTALL_MODE: "side" });
  expect(result.code).toBe(0);
  expect(readFileSync(observed, "utf8")).toBe(previous);
  expect(statSync(path).ino).not.toBe(inode);
  expect(Bun.YAML.parse(readFileSync(path, "utf8"))).toEqual({
    modelRoles: { default: "owner/model" },
    skills: { ignoredSkills: ["cataly-mode"], customDirectories: [join(home, ".omp-cataly/skills")] },
    update: { auto: false },
  });
});

posix.each([
  "- retained\n",
  "retained\n",
  "skills: [retained]\n",
  "skills: retained\n",
  "skills: [\n",
  "null\n",
  "",
  "update: [retained]\n",
  "update: retained\n",
])("a reinstall preserves an invalid owner configuration: %j", (previous) => {
  const { home, install } = setup();
  withOtherCataly(home);
  expect(install({ CATALY_INSTALL_MODE: "side" }).code).toBe(0);
  const path = join(home, ".omp-cataly/omp.yml");
  writeFileSync(path, previous);
  chmodSync(path, 0o640);
  const before = statSync(path);
  const result = install({ CATALY_INSTALL_MODE: "side" });
  expect(result.code).toBe(1);
  expect(result.err).toContain(`Configuration setup held for ${path}`);
  expect(readFileSync(path, "utf8")).toBe(previous);
  expect(statSync(path).mode).toBe(before.mode);
  expect(statSync(path).ino).toBe(before.ino);
  expect(
    readdirSync(join(home, ".omp-cataly")).filter(
      (name) => name.startsWith(".omp.yml.") || name.startsWith("omp.yml."),
    ),
  ).toEqual([]);
});

posix("a merge process failure preserves the owner file and removes only its unpublished replacement", () => {
  const { root, home, install } = setup();
  withOtherCataly(home);
  expect(install({ CATALY_INSTALL_MODE: "side" }).code).toBe(0);
  const path = join(home, ".omp-cataly/omp.yml");
  const previous = "owner: retained\n";
  writeFileSync(path, previous);
  chmodSync(path, 0o640);
  const before = statSync(path);
  const bun = join(root, "bin/bun");
  writeFileSync(
    bun,
    readFileSync(bun, "utf8").replace(
      "#!/bin/sh\n",
      `#!/bin/sh\nif [ "\${1##*/}" = source-configuration.ts ] && [ "\${2:-}" = publish-yaml ]; then echo "fixture merge failure" >&2; exit 23; fi\n`,
    ),
  );
  const result = install({ CATALY_INSTALL_MODE: "side" });
  expect(result.code).toBe(1);
  expect(result.err).toContain("fixture merge failure");
  expect(result.err).toContain(`Configuration setup held for ${path}`);
  expect(readFileSync(path, "utf8")).toBe(previous);
  expect(statSync(path).mode).toBe(before.mode);
  expect(statSync(path).ino).toBe(before.ino);
  expect(
    readdirSync(join(home, ".omp-cataly")).filter(
      (name) => name.startsWith(".omp.yml.") || name.startsWith("omp.yml."),
    ),
  ).toEqual([]);
});

posix("primary installation leaves primary and side owner YAML untouched", () => {
  const { home, install } = setup();
  for (const directory of [".cataly", ".omp-cataly"]) {
    mkdirSync(join(home, directory));
    writeFileSync(join(home, directory, "omp.yml"), "owner: [retained]\n");
  }
  expect(install({ CATALY_INSTALL_MODE: "primary" }).code).toBe(0);
  for (const directory of [".cataly", ".omp-cataly"]) {
    expect(readFileSync(join(home, directory, "omp.yml"), "utf8")).toBe("owner: [retained]\n");
  }
});
